"""## Method notes and limitations

* **ARIMA is non-seasonal here.** Hourly PM2.5 has a strong daily cycle. Plain ARIMA can only approximate it through long AR lags (the grid goes to p = 24), and its multi-day forecasts drift towards a flat level or the long-run mean. Expect good skill at short lead times and mostly level-tracking beyond 1 to 2 days (see the lead-time rows of the test metrics).
* **Regime shift between splits.** The series spans one year. The train block contains the autumn/winter smog season, while validation and especially test fall in the spring decline, so the test period is calmer than most of the training data. Errors and R² are specific to that window.
* **Log transform.** Models are fitted to `log1p(PM2.5)` so forecasts and intervals cannot go negative. Back-transformed point forecasts are medians, not means, and are therefore slightly low in expectation for a skewed series. No bias correction is applied.
* **Confidence interval.** The 95% interval assumes Gaussian errors on the log scale with the fitted ARIMA variance. Real PM2.5 spikes are heavier-tailed, so actual coverage will be below 95% in smog episodes.
* **Order search is bounded.** The grid is broad but finite (see the configuration cell); orders outside it, and seasonal or exogenous-variable (weather) models, are intentionally not searched because this notebook is ARIMA-only.
* **Missing data.** Gaps longer than 6 hours are not filled; ARIMA treats them as missing observations and they are excluded from scoring. Test metrics only use hours with a valid observation.
* **Sensor-spike and zero rules** (cleaning step 4) are judgement-based thresholds, all configurable in the first code cell. Review the spike-episode table before relying on those rules for other stations or years.
* **Timestamps** are used exactly as stored (naive local time); no timezone conversion is applied.
"""