def regression_metrics(y_true, y_pred):
    """RMSE, MAE, MAPE and R2 using NumPy."""
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    m = np.isfinite(y_true) & np.isfinite(y_pred)

    yt, yp = y_true[m], y_pred[m]

    if yt.size == 0:
        return {
            "n": 0,
            "rmse": np.nan,
            "mae": np.nan,
            "mape_pct": np.nan,
            "r2": np.nan
        }

    err = yp - yt
    nz = yt != 0

    ss_tot = np.sum((yt - yt.mean()) ** 2)

    return {
        "n": int(yt.size),
        "rmse": float(np.sqrt(np.mean(err ** 2))),
        "mae": float(np.mean(np.abs(err))),
        "mape_pct": (
            float(np.mean(np.abs(err[nz] / yt[nz])) * 100)
            if nz.any() else np.nan
        ),
        "r2": (
            float(1.0 - np.sum(err ** 2) / ss_tot)
            if ss_tot > 0 else np.nan
        ),
    }


def fit_arima(y, order):
    model = ARIMA(
        y,
        order=order,
        enforce_stationarity=True,
        enforce_invertibility=True
    )

    return model.fit(
        method="statespace",
        method_kwargs={"maxiter": MAXITER}
    )


def rolling_one_step_forecast(res, future_obs, alpha=ALPHA):
    """
    Rolling one-step-ahead forecast.

    At every hour:
      1. Predict the next hour.
      2. Compare prediction with actual observation.
      3. Reveal the actual observation to the model.
      4. Move forward one hour.

    Model parameters remain fixed; only the state is updated.
    """

    future_y = to_model(future_obs)

    frames = []
    current_res = res

    for i in range(len(future_y)):

        # ----------------------------------------------------
        # Predict exactly ONE hour ahead
        # ----------------------------------------------------
        fc = current_res.get_forecast(steps=1)

        ci = fc.conf_int(alpha=alpha)

        pred_model = float(fc.predicted_mean.iloc[0])
        lower_model = float(ci.iloc[0, 0])
        upper_model = float(ci.iloc[0, 1])

        timestamp = future_y.index[i]

        actual_original = future_obs.iloc[i]

        frames.append({
            "timestamp": timestamp,
            "observed": float(actual_original)
                if pd.notna(actual_original) else np.nan,
            "pred": float(from_model(pred_model)),
            "lo": float(from_model(lower_model)),
            "hi": float(from_model(upper_model)),
            "lead_hour": 1
        })

        # ----------------------------------------------------
        # Reveal actual value and update ARIMA state
        # ----------------------------------------------------
        actual = future_y.iloc[i:i+1]

        # Even if actual is NaN, extending advances the model
        # through that timestamp while preserving the missing value.
        current_res = current_res.extend(actual)

    out = pd.DataFrame(frames).set_index("timestamp")

    return out


def evaluate_candidate(order, train_y_, val_obs_):

    p, d, q = order

    rec = {
        "order": f"({p},{d},{q})",
        "p": p,
        "d": d,
        "q": q,
        "status": "ok",
        "reason": "",
        "converged": False,
        "aic": np.nan,
        "bic": np.nan,
        "n_params": np.nan,
        "fit_seconds": np.nan,
        "val_rmse": np.nan,
        "val_mae": np.nan,
        "val_mape_pct": np.nan,
        "val_r2": np.nan,
        "n_val_scored": 0,
        "notes": ""
    }

    t0 = time.perf_counter()

    try:

        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")

            res = fit_arima(train_y_, order)

        rec["fit_seconds"] = round(
            time.perf_counter() - t0, 2
        )

        rec["notes"] = ", ".join(
            sorted({
                w.category.__name__
                for w in caught
            })
        )

        rv = getattr(res, "mle_retvals", None)

        rec["converged"] = (
            True
            if not rv
            else bool(rv.get("converged", False))
        )

        rec["aic"] = float(res.aic)
        rec["bic"] = float(res.bic)
        rec["n_params"] = int(len(res.params))

        # ----------------------------------------------------
        # Exclude non-converged models
        # ----------------------------------------------------
        if not rec["converged"]:

            rec["status"] = "non_converged"

            rec["reason"] = (
                f"optimizer did not converge "
                f"(iterations={rv.get('iterations', '?')}, "
                f"warnflag={rv.get('warnflag', '?')}; "
                f"max {MAXITER})"
            )

            return rec

        # ----------------------------------------------------
        # Check parameters
        # ----------------------------------------------------
        if not (
            np.all(np.isfinite(res.params))
            and np.isfinite(rec["aic"])
        ):

            rec["status"] = "non_finite"

            rec["reason"] = (
                "non-finite parameter estimates "
                "or information criterion"
            )

            return rec

        # ----------------------------------------------------
        # IMPORTANT:
        # Rolling ONE-step validation
        # ----------------------------------------------------
        fc = rolling_one_step_forecast(
            res,
            val_obs_
        )

        if not np.isfinite(
            fc["pred"].to_numpy()
        ).all():

            rec["status"] = "non_finite"

            rec["reason"] = (
                "non-finite validation forecasts"
            )

            return rec

        # ----------------------------------------------------
        # Validation metrics
        # ----------------------------------------------------
        m = regression_metrics(
            fc["observed"],
            fc["pred"]
        )

        if not np.isfinite(m["rmse"]):

            rec["status"] = "non_finite"

            rec["reason"] = (
                "validation RMSE is not finite"
            )

            return rec

        rec.update(
            val_rmse=m["rmse"],
            val_mae=m["mae"],
            val_mape_pct=m["mape_pct"],
            val_r2=m["r2"],
            n_val_scored=m["n"]
        )

    except Exception as exc:

        rec["status"] = "fit_error"

        rec["reason"] = (
            f"{type(exc).__name__}: "
            f"{str(exc)[:140]}"
        )

        rec["fit_seconds"] = round(
            time.perf_counter() - t0,
            2
        )

    return rec


