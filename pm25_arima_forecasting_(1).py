"""## 2. Read the UET data from the three layouts

The workbooks do not share one layout, so the reader finds things by content instead of by fixed position:

* **Jan-Apr 2026 and May 2026**: one sheet, a title row, a header row starting with `Time`, one column per station. The UET column is the header that contains `UET`. The May workbook also has `max` / `min` / `avg` footer rows, which are not timestamps and are dropped (and counted).
* **Jun-Dec 2025**: one sheet per station. Only the sheet for UET is read (sheet name `uet(LAHORE)`); the header row is `timestamp` / `pm25` below a few blank or label rows, and rows are not in time order.

**Timestamps** may arrive as real datetimes, as **Excel serial numbers** (days since 1899-12-30, optionally stored as text), or as ISO-style text. All three are converted. **Values** may be numbers, numbers stored as text (655 in the Jun-Dec sheet), blanks, or junk text; text that is a valid number is converted.
"""

banner("Step 2/8: reading UET columns/sheets")

EXCEL_EPOCH = pd.Timestamp("1899-12-30")      # Excel 1900 date system (serial 1 = 1900-01-01 after the leap-year quirk)
_UET_RE = re.compile(r"(?<![a-z])uet(?![a-z])", re.I)
_TIME_HEADERS = {"time", "timestamp", "date & time", "date and time", "datetime", "date"}

def parse_one_timestamp(v):
    """Return (Timestamp or NaT, kind). kind in: datetime, excel_serial, text, blank, unparseable."""
    if v is None or (not isinstance(v, str) and pd.isna(v)):
        return pd.NaT, "blank"
    if isinstance(v, (dt.datetime, np.datetime64)):
        return pd.Timestamp(v), "datetime"
    if isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool):
        if np.isfinite(v) and 20000 <= float(v) <= 80000:                 # 1954..2118 as Excel serial
            return EXCEL_EPOCH + pd.to_timedelta(float(v), unit="D"), "excel_serial"
        return pd.NaT, "unparseable"
    if isinstance(v, str):
        s = v.strip()
        if s == "":
            return pd.NaT, "blank"
        try:                                                              # serial number stored as text
            f = float(s)
            if 20000 <= f <= 80000:
                return EXCEL_EPOCH + pd.to_timedelta(f, unit="D"), "excel_serial"
            return pd.NaT, "unparseable"
        except ValueError:
            pass
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            ts = pd.to_datetime(s, errors="coerce")
        return (ts, "text") if not pd.isna(ts) else (pd.NaT, "unparseable")
    return pd.NaT, "unparseable"

def parse_one_value(v):
    """Return (float, kind). kind in: number, numeric_text, blank, non_numeric_text, non_finite."""
    if v is None or (not isinstance(v, str) and pd.isna(v)):
        return np.nan, "blank"
    if isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool):
        return (float(v), "number") if np.isfinite(v) else (np.nan, "non_finite")
    if isinstance(v, str):
        s = v.strip().replace(",", "")
        if s == "":
            return np.nan, "blank"
        try:
            f = float(s)
            return (f, "numeric_text") if np.isfinite(f) else (np.nan, "non_finite")
        except ValueError:
            return np.nan, "non_numeric_text"
    return np.nan, "non_numeric_text"

