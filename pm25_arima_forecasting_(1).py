"""## 5. ARIMA grid search on the validation set

**Grid** (documented, not hand-picked): `p` in {0, 1, 2, 3, 4, 6, 8, 12, 24}, `d` in {0, 1}, `q` in {0, 1, 2, 3, 4, 6}, which is **108 candidates**. `p` runs well beyond 2 on purpose: lags 12 and 24 let an AR model reach the daily cycle, which a plain (non-seasonal) ARIMA cannot represent any other way. The grid is dense at short lags and sparse at long lags to keep the run time sensible.

**Per candidate**
1. Fit `statsmodels.tsa.arima.model.ARIMA(order)` on the training data (exact Gaussian likelihood via the state-space Kalman filter, up to 200 optimiser iterations).
2. **Exclude and record the reason** if the fit raises an exception, the optimiser does not converge, or parameters / forecasts / metrics are not finite.
3. Otherwise score it with the rolling-origin protocol over the validation period (168-hour forecasts, origin moved forward every 168 hours, parameters fixed from training).
4. Metrics are computed on the original ug/m3 scale with NumPy, on hours that have a valid observed value.

Progress is printed after every candidate.
"""

