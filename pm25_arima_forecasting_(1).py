def _find_time_header(raw, max_scan=15):
    for i in range(min(max_scan, len(raw))):
        for j, cell in enumerate(raw.iloc[i]):
            if isinstance(cell, str) and cell.strip().lower() in _TIME_HEADERS:
                return i, j
    return None

def _find_uet_column(raw, hdr_row, time_col, sheet_name):
    hdr = raw.iloc[hdr_row]
    for j, cell in enumerate(hdr):                                   # multi-station layout: UET is named in the header
        if j != time_col and isinstance(cell, str) and _UET_RE.search(cell):
            return j
    label_above = any(isinstance(c, str) and _UET_RE.search(c) for c in raw.iloc[:hdr_row].to_numpy().ravel())
    if _UET_RE.search(sheet_name) or label_above:                    # single-station layout: the whole sheet is UET
        for j in range(time_col + 1, raw.shape[1]):
            cell = hdr.iloc[j]
            if isinstance(cell, str) and "pm" in cell.lower():
                return j
        return time_col + 1
    return None

def read_uet_workbook(path):
    xl = pd.ExcelFile(path)
    frames = []
    for sheet in xl.sheet_names:
        raw = pd.read_excel(xl, sheet_name=sheet, header=None, dtype=object)
        loc = _find_time_header(raw)
        if loc is None:
            continue
        hdr_row, time_col = loc
        val_col = _find_uet_column(raw, hdr_row, time_col, sheet)
        if val_col is None:
            continue
        body = raw.iloc[hdr_row + 1:, [time_col, val_col]].copy()
        body.columns = ["raw_time", "raw_value"]
        body = body.dropna(how="all")                                # fully blank rows
        body["sheet"] = sheet
        frames.append(body)
    if not frames:
        raise ValueError(f"No {TARGET_STATION} data found in {path.name}")
    return pd.concat(frames, ignore_index=True)

